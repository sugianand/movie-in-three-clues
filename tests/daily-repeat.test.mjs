import assert from 'node:assert/strict';
import {isRepeatedDailyGuess,dailyRepeatMessage} from '../lib/daily-repeat.ts';
import {openDaily,dailyAction} from '../lib/daily.ts';
assert(isRepeatedDailyGuess('  WALL-e! ',['Wall E']));
assert(isRepeatedDailyGuess('AMELIE',['Amélie']));
assert(!isRepeatedDailyGuess('Alien',['Aliens',null]));
assert(!isRepeatedDailyGuess('Rocky II',['Rocky']));
assert(!isRepeatedDailyGuess('Rocky 2',['Rocky 3']));
assert(!isRepeatedDailyGuess('東京',['大阪']));
assert(isRepeatedDailyGuess('東京!',['東京']));
assert(!isRepeatedDailyGuess('!!!',['???']));
assert(!isRepeatedDailyGuess('Arrival'));
const p=openDaily(null,Date.parse('2026-10-19T12:00:00Z'));
dailyAction(p,'guess','Imaginary Movie 987');
const before=JSON.stringify(p);
assert.throws(()=>dailyAction(p,'guess','IMAGINARY-MOVIE 987!'),{message:dailyRepeatMessage});
assert.equal(JSON.stringify(p),before,'Repeat cannot change marks, stage, points or history');
dailyAction(p,'skip');
const last=JSON.stringify(p);
assert.throws(()=>dailyAction(p,'guess','Imaginary Movie 987'),{message:dailyRepeatMessage});
assert.equal(JSON.stringify(p),last,'Repeat cannot end the final clue');
dailyAction(p,'guess',p.title);assert.equal(p.score,100);
const legacy=openDaily(null,Date.parse('2026-10-19T12:00:00Z'));delete legacy.guesses;
dailyAction(legacy,'guess',legacy.title);assert.equal(legacy.score,300);
const next=openDaily(p,Date.parse('2026-10-20T12:00:00Z'));
assert.doesNotThrow(()=>dailyAction(next,'guess','Imaginary Movie 987'));
console.log('Daily repeats preserve clues, points and history; punctuation, accents, sequels, legacy passes and new days covered.');
